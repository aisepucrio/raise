package github

import "raise/internal/platform"

var _ platform.DatasetProvider = (*Platform)(nil)

// Columns shared by most GitHub datasets. raw_payload is left out of every
// dataset: it is large, and its fields are queried in PostgreSQL instead.
func mined(prefix string) []platform.Column {
	return []platform.Column{
		platform.TimeCol("first_mined_at").Expression(prefix + "first_mined_at"),
		platform.TimeCol("last_mined_at").Expression(prefix + "last_mined_at"),
	}
}

func cols(groups ...[]platform.Column) []platform.Column {
	var out []platform.Column
	for _, g := range groups {
		out = append(out, g...)
	}
	return out
}

